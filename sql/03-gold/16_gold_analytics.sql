-- ============================================================================
-- 02. GOLD PRODUCT PERFORMANCE
-- Business question:
-- Which products generate the most net revenue, units sold and margin?
--
-- Grain: one row per active product with completed-order activity
-- ============================================================================

CREATE OR REPLACE TABLE gold_product_performance AS
SELECT
    pc.prod_code,
    pc.product_name,

    SUM(oic.quantity) AS units_sold,

    ROUND(
        SUM(
            oic.quantity
            * oic.unit_price
            * (1 - oic.discount / 100)
        ),
        2
    ) AS net_revenue,

    ROUND(
        SUM(
            oic.quantity
            * (
                oic.unit_price * (1 - oic.discount / 100)
                - pc.unit_cost
            )
        ),
        2
    ) AS total_margin,

    ROUND(
        SUM(
            oic.quantity
            * (
                oic.unit_price * (1 - oic.discount / 100)
                - pc.unit_cost
            )
        ) / SUM(oic.quantity),
        2
    ) AS margin_per_unit

FROM products_clean AS pc
INNER JOIN order_items_clean AS oic
    ON pc.prod_code = oic.product_code
INNER JOIN orders_clean AS oc
    ON oic.order_no = oc.order_no
WHERE pc.active = 'Y'
  AND oc.status = 'completed'
GROUP BY
    pc.prod_code,
    pc.product_name;


-- Validation

SELECT *
FROM gold_product_performance
ORDER BY margin_per_unit DESC;

SELECT COUNT(*) AS row_count
FROM gold_product_performance;

SELECT COUNT(DISTINCT prod_code) AS distinct_products
FROM gold_product_performance;

SELECT
    prod_code,
    COUNT(*) AS occurrences
FROM gold_product_performance
GROUP BY prod_code
HAVING COUNT(*) > 1;


-- Export

COPY gold_product_performance
TO '/mnt/c/Users/Lenovo/DataProjects/data-quality-pipeline/data/04-gold/gold_product_performance.parquet'
(FORMAT PARQUET);


-- Read-back verification

