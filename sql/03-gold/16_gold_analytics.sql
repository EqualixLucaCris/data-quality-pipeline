-- ============================================================================
-- Data Quality Pipeline
-- Gold Analytics Layer
-- File: 16_gold_analytics.sql
--
-- Purpose:
--   Build, validate, export and verify the five Gold analytical datasets.
--
-- Common business rules:
--   - Gold consumes validated Silver tables only.
--   - Revenue analysis considers completed orders.
--   - Product-based profitability analysis considers active products.
--   - Net revenue:
--       quantity * unit_price * (1 - discount / 100)
--   - Total margin:
--       quantity * (effective_selling_price - unit_cost)
--   - Monetary metrics are rounded to 2 decimal places.
-- ============================================================================


-- ============================================================================
-- 01. GOLD COMPLETED ORDER REVENUE
-- Business question:
-- How much net revenue was generated by each completed order?
--
-- Grain: one row per completed order
-- ============================================================================

CREATE OR REPLACE TABLE gold_completed_order_revenue AS
SELECT
    oc.order_no,
    oc.order_date,
    ROUND(
        SUM(
            oic.quantity
            * oic.unit_price
            * (1 - oic.discount / 100)
        ),
        2
    ) AS net_revenue
FROM orders_clean AS oc
INNER JOIN order_items_clean AS oic
    ON oc.order_no = oic.order_no
WHERE oc.status = 'completed'
GROUP BY
    oc.order_no,
    oc.order_date;


-- Validation

SELECT *
FROM gold_completed_order_revenue
ORDER BY net_revenue DESC;

SELECT COUNT(*) AS row_count
FROM gold_completed_order_revenue;

SELECT COUNT(DISTINCT order_no) AS distinct_orders
FROM gold_completed_order_revenue;

SELECT
    order_no,
    COUNT(*) AS occurrences
FROM gold_completed_order_revenue
GROUP BY order_no
HAVING COUNT(*) > 1;


-- Export

COPY gold_completed_order_revenue
TO '/mnt/c/Users/Lenovo/DataProjects/data-quality-pipeline/data/04-gold/gold_completed_order_revenue.parquet'
(FORMAT PARQUET);


-- Read-back verification

